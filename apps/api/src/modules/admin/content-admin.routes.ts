// Content management: edit question banks and teaching pages in the database — no deploy needed.
import type { FastifyPluginAsyncZod } from 'fastify-type-provider-zod';
import { z } from 'zod';
import { and, asc, count, eq } from 'drizzle-orm';
import engine from '@stepwise/engine';
import { AnyObject, ItemCreateBody, ItemPatchBody, TopicPatchBody, StylePatchBody, LearnPutBody, Ok, type BankItem } from '@stepwise/shared';
import * as s from '../../db/schema.js';
import type { Services } from '../../services.js';
import { fail } from '../../core/errors.js';
import { bumpContentVersion } from '../../content/import.js';
import { audit } from '../common/audit.js';

// An item is only accepted if its own canonical answer is marked correct and a nonsense answer is not.
function assertWellFormed(body: BankItem) {
  if ((body.type === 'mcq') && body.correct >= body.options.length) fail(400, 'Correct option is out of range');
  if (body.type === 'multi' && body.correct.some((i) => i >= body.options.length)) fail(400, 'Correct option is out of range');
  if (body.type === 'short' && !(body.accept?.length || body.keywords?.length)) fail(400, 'Short answers need accepted answers or keywords');
  for (let i = 0; i < 4; i++) {
    const q = engine.fromItem(body as never, i);
    if (!engine.checkAnswer(q.check, q.answer)) fail(400, 'The item’s own answer is not marked correct — check the answer fields');
    if (engine.checkAnswer(q.check, 'zzqx')) fail(400, 'This item would accept nonsense answers');
  }
}

const routes: FastifyPluginAsyncZod<{ svc: Services }> = async (app, { svc }) => {
  const { db } = svc.deps;
  const admin = { roles: ['admin' as const] }; const tags = ['content-admin'];
  const changed = async (actor: { id: string; name: string }, what: string) => { await bumpContentVersion(db); await (svc.deps.content as { reload?: () => Promise<void> }).reload?.(); await audit(db, actor, 'content-edit', what); };

  app.get('/admin/content/topics/:id', { config: admin, schema: { tags, params: z.object({ id: z.string() }), response: { 200: AnyObject } } }, async (req) => {
    const [t] = await db.select().from(s.topics).where(eq(s.topics.id, req.params.id));
    if (!t) fail(404, 'Topic not found');
    const styles = await db.select().from(s.styles).where(eq(s.styles.topicId, t!.id)).orderBy(asc(s.styles.sortOrder));
    const counts = await db.select({ styleId: s.items.styleId, c: count() }).from(s.items).where(eq(s.items.active, true)).groupBy(s.items.styleId);
    const [lp] = await db.select().from(s.learnPages).where(eq(s.learnPages.topicId, t!.id));
    return { topic: t, styles: styles.map((x) => ({ ...x, items: Number(counts.find((c) => c.styleId === x.id)?.c || 0) })), learn: lp?.content || null };
  });
  app.patch('/admin/content/topics/:id', { config: admin, schema: { tags, params: z.object({ id: z.string() }), body: TopicPatchBody, response: { 200: Ok } } }, async (req) => {
    const r = await db.update(s.topics).set(req.body).where(eq(s.topics.id, req.params.id)).returning({ id: s.topics.id });
    if (!r.length) fail(404, 'Topic not found');
    await changed(req.user!, `topic ${req.params.id}`); return { ok: true as const };
  });
  app.patch('/admin/content/styles/:id', { config: admin, schema: { tags, params: z.object({ id: z.string() }), body: StylePatchBody, response: { 200: Ok } } }, async (req) => {
    const r = await db.update(s.styles).set(req.body).where(eq(s.styles.id, req.params.id)).returning({ id: s.styles.id });
    if (!r.length) fail(404, 'Style not found');
    await changed(req.user!, `style ${req.params.id}`); return { ok: true as const };
  });
  app.get('/admin/content/styles/:id/items', { config: admin, schema: { tags, params: z.object({ id: z.string() }), response: { 200: AnyObject } } }, async (req) => {
    const [st] = await db.select().from(s.styles).where(eq(s.styles.id, req.params.id));
    if (!st) fail(404, 'Style not found');
    return { style: st, items: await db.select().from(s.items).where(eq(s.items.styleId, st!.id)).orderBy(asc(s.items.sortOrder)) };
  });
  app.post('/admin/content/styles/:id/items', { config: admin, schema: { tags, summary: 'Add a question to a bank', params: z.object({ id: z.string() }), body: ItemCreateBody, response: { 200: AnyObject } } }, async (req) => {
    const [st] = await db.select().from(s.styles).where(eq(s.styles.id, req.params.id));
    if (!st) fail(404, 'Style not found');
    if (st!.source !== 'bank') fail(400, 'This style is generated by code; it has no question bank');
    assertWellFormed(req.body.body);
    const [{ c }] = await db.select({ c: count() }).from(s.items).where(eq(s.items.styleId, st!.id));
    const [row] = await db.insert(s.items).values({ id: `${st!.id}~u${Date.now().toString(36)}`, styleId: st!.id, type: req.body.body.type, body: req.body.body, sortOrder: Number(c) }).returning();
    await changed(req.user!, `item added to ${st!.id}`);
    return { item: row };
  });
  app.patch('/admin/content/items/:id', { config: admin, schema: { tags, params: z.object({ id: z.string() }), body: ItemPatchBody, response: { 200: AnyObject } } }, async (req) => {
    if (req.body.body) assertWellFormed(req.body.body);
    const [row] = await db.update(s.items).set({ ...(req.body.body ? { body: req.body.body, type: req.body.body.type } : {}), ...(req.body.active !== undefined ? { active: req.body.active } : {}), updatedAt: new Date().toISOString() })
      .where(eq(s.items.id, req.params.id)).returning();
    if (!row) fail(404, 'Item not found');
    await changed(req.user!, `item ${req.params.id}`);
    return { item: row };
  });
  app.delete('/admin/content/items/:id', { config: admin, schema: { tags, params: z.object({ id: z.string() }), response: { 200: Ok } } }, async (req) => {
    const r = await db.delete(s.items).where(and(eq(s.items.id, req.params.id))).returning({ id: s.items.id });
    if (!r.length) fail(404, 'Item not found');
    await changed(req.user!, `item deleted ${req.params.id}`); return { ok: true as const };
  });
  app.put('/admin/content/learn/:topicId', { config: admin, schema: { tags, summary: 'Replace a topic’s teaching page', params: z.object({ topicId: z.string() }), body: LearnPutBody, response: { 200: Ok } } }, async (req) => {
    const [t] = await db.select({ id: s.topics.id }).from(s.topics).where(eq(s.topics.id, req.params.topicId));
    if (!t) fail(404, 'Topic not found');
    await db.insert(s.learnPages).values({ topicId: t.id, content: req.body.content }).onConflictDoUpdate({ target: s.learnPages.topicId, set: { content: req.body.content, updatedAt: new Date().toISOString() } });
    await changed(req.user!, `learn page ${t.id}`); return { ok: true as const };
  });
};
export default routes;
